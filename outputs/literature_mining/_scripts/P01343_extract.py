def calc_sumddt(row):
    """SumDDT = opDDT + ppDDT + opDDD + ppDDD + opDDE + ppDDE"""
    return round(row[5] + row[6] + row[7] + row[8] + row[9] + row[10], 4)

def calc_endosulfan(row):
    return round(row[2] + row[3], 4)

